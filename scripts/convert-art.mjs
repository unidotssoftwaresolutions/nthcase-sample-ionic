// Converts the shared drawings in art/ into the forms each part of the app needs. art/ itself is never changed.
//
//   src/art/art.generated.ts                     every icon and product glyph as path data, for inline <svg>
//   android/app/src/main/res/drawable/*.xml      the launcher mark as adaptive-icon layers, and the notification icon
//   android/app/src/main/res/values/launcher.xml the launcher background colour
//   ios/App/App/Assets.xcassets/AppIcon…         the launcher mark as the 1024 pt app icon
//   ios/App/App/Assets.xcassets/Splash…          the launcher mark centred on card stock, for the launch screen
//
// The PNGs are drawn by Playwright's Chromium (a dev dependency, never shipped). Run: npm run art
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const art = join(root, 'art');

function attr(svg, name) {
  const match = new RegExp(`\\s${name}="([^"]*)"`).exec(svg);
  if (!match) throw new Error(`no ${name} in ${svg.slice(0, 80)}`);
  return match[1];
}

async function strokes(folder) {
  const names = (await readdir(join(art, folder))).filter((f) => f.endsWith('.svg')).sort();
  const out = {};
  for (const file of names) {
    const svg = await readFile(join(art, folder, file), 'utf8');
    const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
    if (paths.length !== 1) throw new Error(`${folder}/${file}: expected one stroked path, found ${paths.length}`);
    out[file.replace(/\.svg$/, '')] = { d: paths[0], viewBox: attr(svg, 'viewBox'), stroke: Number(attr(svg, 'stroke-width')) };
  }
  return out;
}

async function writeTs() {
  const icons = await strokes('icons');
  const glyphs = await strokes('glyphs');
  const lines = [
    '// Generated by scripts/convert-art.mjs from art/icons/*.svg and art/glyphs/*.svg. Do not edit; run `npm run art`.',
    '// Each drawing is one stroked path; its colour comes from the CSS `color` where it is drawn.',
    '',
    'export interface Stroke {',
    '  d: string;',
    '  viewBox: string;',
    '  stroke: number;',
    '}',
    '',
    `export const ICONS = ${JSON.stringify(icons, null, 2)} as const satisfies Record<string, Stroke>;`,
    '',
    `export const GLYPHS = ${JSON.stringify(glyphs, null, 2)} as const satisfies Record<string, Stroke>;`,
    '',
    'export type IconName = keyof typeof ICONS;',
    'export type GlyphName = keyof typeof GLYPHS;',
    '',
  ];
  await mkdir(join(root, 'src/art'), { recursive: true });
  await writeFile(join(root, 'src/art/art.generated.ts'), lines.join('\n'));
  console.log(`src/art/art.generated.ts: ${Object.keys(icons).length} icons, ${Object.keys(glyphs).length} glyphs`);
}

/** The launcher mark's three shapes, read from art/launcher.svg: the ground, the drawer front, the label, the pull. */
async function launcher() {
  const svg = await readFile(join(art, 'launcher.svg'), 'utf8');
  const ground = /<rect[^>]*fill="(#[0-9A-Fa-f]{6})"/.exec(svg)[1];
  const paths = [...svg.matchAll(/<path([^>]*)\/>/g)].map((m) => ({
    d: attr(m[1], 'd'),
    fill: attr(m[1], 'fill'),
    stroke: /stroke="/.test(m[1]) ? attr(m[1], 'stroke') : null,
    width: /stroke-width="/.test(m[1]) ? attr(m[1], 'stroke-width') : null,
    cap: /stroke-linecap="/.test(m[1]) ? attr(m[1], 'stroke-linecap') : null,
  }));
  return { svg, ground, paths };
}

function vectorPath(p, colour) {
  const parts = [`android:pathData="${p.d}"`];
  if (p.fill !== 'none') parts.push(`android:fillColor="${colour ?? p.fill}"`);
  else parts.push('android:fillColor="#00000000"');
  if (p.stroke) parts.push(`android:strokeColor="${colour ?? p.stroke}"`, `android:strokeWidth="${p.width}"`);
  if (p.cap === 'round') parts.push('android:strokeLineCap="round"');
  return `    <path ${parts.join(' ')} />`;
}

async function writeAndroid() {
  const res = join(root, 'android/app/src/main/res');
  if (!existsSync(res)) return console.log('android/ not there yet: skipped');
  const { ground, paths } = await launcher();
  const head = (size, port) =>
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="${size}dp" android:height="${size}dp" android:viewportWidth="${port}" android:viewportHeight="${port}">`;
  const note = '<!-- Generated by scripts/convert-art.mjs from art/launcher.svg. -->';
  await mkdir(join(res, 'drawable'), { recursive: true });
  await writeFile(
    join(res, 'drawable/ic_launcher_foreground.xml'),
    `<?xml version="1.0" encoding="utf-8"?>\n${note}\n${head(108, 108)}\n${paths.map((p) => vectorPath(p)).join('\n')}\n</vector>\n`,
  );
  // Themed icons draw the mark in one colour: the drawer front and its label holder, without the pull.
  await writeFile(
    join(res, 'drawable/ic_launcher_monochrome.xml'),
    `<?xml version="1.0" encoding="utf-8"?>\n${note}\n${head(108, 108)}\n${paths.slice(0, 2).map((p) => vectorPath(p, '#FFFFFFFF')).join('\n')}\n</vector>\n`,
  );
  // The status-bar icon: white on transparent, as Android requires; the label holder is cut out of the drawer front.
  const front = paths[0].d;
  const label = paths[1].d;
  await writeFile(
    join(res, 'drawable/ic_stat_mossgrove.xml'),
    `<?xml version="1.0" encoding="utf-8"?>\n${note}\n${head(24, 108)}\n` +
      `    <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="${front} ${label}" />\n</vector>\n`,
  );
  await mkdir(join(res, 'mipmap-anydpi-v26'), { recursive: true });
  const adaptive = `<?xml version="1.0" encoding="utf-8"?>\n${note}\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n    <background android:drawable="@color/ic_launcher_background" />\n    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n</adaptive-icon>\n`;
  await writeFile(join(res, 'mipmap-anydpi-v26/ic_launcher.xml'), adaptive);
  await writeFile(join(res, 'mipmap-anydpi-v26/ic_launcher_round.xml'), adaptive);
  await mkdir(join(res, 'values'), { recursive: true });
  await writeFile(
    join(res, 'values/ic_launcher_background.xml'),
    `<?xml version="1.0" encoding="utf-8"?>\n${note}\n<resources>\n    <color name="ic_launcher_background">${ground}</color>\n    <color name="splash_background">#F7F9F7</color>\n</resources>\n`,
  );
  console.log('android: launcher layers, monochrome, notification icon');
}

async function writeIos() {
  const assets = join(root, 'ios/App/App/Assets.xcassets');
  if (!existsSync(assets)) return console.log('ios/ not there yet: skipped');
  const { svg } = await launcher();
  const { chromium } = await import('@playwright/test');
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ deviceScaleFactor: 1 });
    // The app icon: the mark edge to edge (iOS rounds the corners itself), no transparency.
    const iconSvg = svg.replace(/width="\d+" height="\d+"/, 'width="1024" height="1024"');
    await page.setViewportSize({ width: 1024, height: 1024 });
    await page.setContent(`<html><body style="margin:0">${iconSvg}</body></html>`);
    const icon = await page.locator('svg').screenshot({ omitBackground: false });
    const iconDir = join(assets, 'AppIcon.appiconset');
    await mkdir(iconDir, { recursive: true });
    await writeFile(join(iconDir, 'AppIcon-512@2x.png'), icon);
    await writeFile(
      join(iconDir, 'Contents.json'),
      JSON.stringify({ images: [{ filename: 'AppIcon-512@2x.png', idiom: 'universal', platform: 'ios', size: '1024x1024' }], info: { author: 'xcode', version: 1 } }, null, 2) + '\n',
    );
    // The launch screen: the same mark, 256 pt, on card stock; light and dark.
    const splashDir = join(assets, 'Splash.imageset');
    await mkdir(splashDir, { recursive: true });
    await page.setViewportSize({ width: 2732, height: 2732 });
    const files = [];
    for (const [suffix, ground] of [['', '#F7F9F7'], ['-dark', '#101413']]) {
      const mark = svg.replace(/width="\d+" height="\d+"/, 'width="768" height="768"');
      await page.setContent(
        `<html><body style="margin:0;width:2732px;height:2732px;display:flex;align-items:center;justify-content:center;background:${ground}">${mark}</body></html>`,
      );
      const png = await page.screenshot({ clip: { x: 0, y: 0, width: 2732, height: 2732 } });
      const name = `splash-2732x2732${suffix}.png`;
      await writeFile(join(splashDir, name), png);
      files.push([suffix, name]);
    }
    const images = [];
    for (const scale of ['1x', '2x', '3x']) {
      images.push({ idiom: 'universal', filename: files[0][1], scale });
      images.push({ appearances: [{ appearance: 'luminosity', value: 'dark' }], idiom: 'universal', filename: files[1][1], scale });
    }
    await writeFile(join(splashDir, 'Contents.json'), JSON.stringify({ images, info: { author: 'xcode', version: 1 } }, null, 2) + '\n');
    console.log('ios: AppIcon 1024, launch-screen mark light and dark');
  } finally {
    await browser.close();
  }
}

await writeTs();
if (!process.argv.includes('--ts-only')) {
  await writeAndroid();
  await writeIos();
}
